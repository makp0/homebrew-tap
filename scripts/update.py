#!/usr/bin/env python3
"""Generate switchpack's formula from a published release and its checksum file."""
import json
import os
from pathlib import Path
import re
import urllib.request

REPO = "makp0/switchpack"
PLATFORMS = [("macos", "darwin"), ("linux", "linux")]
ARCHES = [("arm", "arm64"), ("intel", "x64")]


def fetch(url):
    headers = {"User-Agent": "switchpack-homebrew-updater"}
    if url.startswith("https://api.github.com/") and os.environ.get("GH_TOKEN"):
        headers["Authorization"] = "Bearer " + os.environ["GH_TOKEN"]
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60) as response:
        return response.read()


def formula(tag, checksums):
    if not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
        raise ValueError("Expected a stable vMAJOR.MINOR.PATCH release tag")
    sums = {}
    for line in checksums.splitlines():
        match = re.fullmatch(r"([a-f0-9]{64})  (switchpack-(?:darwin|linux)-(?:arm64|x64)\.tar\.gz)", line)
        if not match or match[2] in sums:
            raise ValueError("Invalid or duplicate release checksum")
        sums[match[2]] = match[1]
    expected = {f"switchpack-{platform}-{arch}.tar.gz" for _, platform in PLATFORMS for _, arch in ARCHES}
    if set(sums) != expected:
        raise ValueError("Release must contain all four platform archives")
    lines = [
        "# Generated by scripts/update.py. Do not edit checksums by hand.",
        "class Switchpack < Formula",
        '  desc "Declarative Nintendo Switch homebrew manager"',
        '  homepage "https://github.com/makp0/switchpack"',
        f'  version "{tag[1:]}"',
        '  license "MIT"',
        '',
        '  depends_on "libmtp"',
        '  on_macos do',
        '    depends_on macos: :sequoia',
        '  end',
    ]
    for os_name, platform in PLATFORMS:
        lines += ["", f"  on_{os_name} do"]
        for cpu, arch in ARCHES:
            name = f"switchpack-{platform}-{arch}.tar.gz"
            lines += [f"    on_{cpu} do", f'      url "https://github.com/{REPO}/releases/download/{tag}/{name}"', f'      sha256 "{sums[name]}"', "    end"]
        lines += ["  end"]
    lines += ['''
  def install
    bin.install "switchpack"
    mtp = Formula["libmtp"]
    system ENV.cc, "-std=c11", "-D_DEFAULT_SOURCE", "-O2", "native/mtp-transfer.c",
           "-I#{mtp.opt_include}", "-L#{mtp.opt_lib}", "-lmtp", "-o", "switchpack-mtp"
    bin.install "switchpack-mtp"
    pkgshare.install "switchpack.json", "switchpack.lock.json"
    doc.install "README.md", "LICENSE", "THIRD_PARTY_NOTICES.md", "licenses"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/switchpack --version")
    system bin/"switchpack", "init"
    assert_path_exists testpath/"switchpack.json"
    mkdir "sd"
    assert_match "unlocked", shell_output("#{bin}/switchpack status --target sd")
  end
end
''']
    return "\n".join(lines)


if __name__ == "__main__":
    release = json.loads(fetch(f"https://api.github.com/repos/{REPO}/releases/latest"))
    tag = release["tag_name"]
    # Construct the public GitHub URL rather than trusting arbitrary asset URLs.
    if not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
        raise ValueError("Invalid release tag")
    checksums = fetch(f"https://github.com/{REPO}/releases/download/{tag}/SHA256SUMS").decode()
    output = Path(__file__).resolve().parent.parent / "Formula/switchpack.rb"
    output.parent.mkdir(exist_ok=True)
    output.write_text(formula(tag, checksums))
    print(f"Updated switchpack formula to {tag}")
